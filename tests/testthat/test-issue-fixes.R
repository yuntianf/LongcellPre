test_that("mapping handles spaces and preserves a complete prior BAM on failure", {
  skip_on_os("windows")
  skip_if(any(Sys.which(c("minimap2","samtools")) == ""))
  folder <- tempfile("mapping with spaces "); dir.create(folder)
  on.exit(unlink(folder,recursive=TRUE))
  set.seed(43)
  seq <- paste(sample(c("A","C","G","T"),2000,TRUE),collapse="")
  fa <- file.path(folder,"reference with spaces.fa")
  fq <- file.path(folder,"reads with spaces.fq")
  writeLines(c(">chr1",seq),fa)
  writeLines(c("@r",substr(seq,401,1400),"+",strrep("~",1000)),fq)
  mm <- file.path(folder,"minimap tool")
  st <- file.path(folder,"samtools tool")
  file.symlink(Sys.which("minimap2"),mm); file.symlink(Sys.which("samtools"),st)
  bam <- file.path(folder,"output with spaces.bam")
  fastqMap(fq,bam,fa,minimap2=mm,samtools=st,minimap2_thread=1,samtools_thread=1)
  expect_true(valid_bam(bam,st))
  expect_false(file.exists(paste0(bam,".bam")))
  prior <- tools::md5sum(c(bam,paste0(bam,".bai")))
  fail <- file.path(folder,"failed aligner")
  writeLines(c("#!/bin/sh","printf '@HD\\tVN:1.6\\n@SQ\\tSN:chr1\\tLN:2000\\n'","exit 23"),fail)
  Sys.chmod(fail,"0755")
  expect_error(fastqMap(fq,bam,fa,minimap2=fail,samtools=st,minimap2_thread=1,samtools_thread=1),"exit 23")
  expect_identical(tools::md5sum(c(bam,paste0(bam,".bai"))),prior)
})

test_that("graph budget reaches workers and failed genes get a QC file", {
  folder <- tempfile(); dir.create(folder)
  on.exit(unlink(folder,recursive=TRUE))
  previous <- future::plan()
  on.exit(future::plan(previous),add=TRUE)
  future::plan(future::multisession,workers=2)
  data <- data.frame(gene="g",barcode="c",umi=c("AAAA","AAAT","AATT","ATTT"),isoform="1,100",polyA=1)
  qual <- data.frame(needle=4,count=4)
  bed <- data.frame(gene="g",strand="+")
  expect_error(umi_count_parallel(data,qual,folder,bed,cores=2,sim_thresh=1,
                               splice_site_thresh=0,max_graph_edges=1),"failed for 1 gene")
  qc <- read.delim(file.path(folder,"umi_qc.tsv"))
  expect_identical(qc$status,"failed")
  expect_match(qc$message,"max_graph_edges")
  expect_false(file.exists(file.path(folder,"iso_count.txt")))
})
