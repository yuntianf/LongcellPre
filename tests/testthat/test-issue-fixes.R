test_that("indexed FASTA export preserves names, values, Ns and orientation across batches", {
  folder <- tempfile(); dir.create(folder)
  on.exit(unlink(folder,recursive=TRUE))
  fa <- file.path(folder,"ref.fa")
  writeLines(c(">chr1","ACGTNNACGT"),fa)
  genome <- load_genome(NULL,fa)
  expect_identical(as.character(reference_seq(genome,"chr1",2,8,"-")),"GTNNACG")
  mat <- data.frame(cell=c("c1","c2"),gene="g1",isoform=c("1,7","4,10"),
                    count=c(11,3),polyA=c(1,0))
  bed <- data.frame(gene="g1",chr="chr1",strand="-")
  full <- isoformCount2Reads(mat,genome,bed,file.path(folder,"large.gz"))
  n <- isoformCount2Reads(mat,genome,bed,file.path(folder,"small.gz"),
          batch_reads=2,batch_bases=10,return_reads=FALSE,
          annotation_file=file.path(folder,"anno.csv"),qc_file=file.path(folder,"qc.tsv"))
  small <- ShortRead::readFastq(file.path(folder,"small.gz"))
  expect_equal(n,14)
  expect_identical(as.character(ShortRead::sread(small)),as.character(ShortRead::sread(full)))
  expect_identical(as.character(ShortRead::id(small)),as.character(ShortRead::id(full)))
  expect_identical(read.csv(file.path(folder,"anno.csv"))$qname,as.character(ShortRead::id(full)))
  expect_equal(read.delim(file.path(folder,"qc.tsv"))$reference_N_bases,28)
  custom <- mat
  custom$isoform <- gsub(",",":",custom$isoform,fixed=TRUE)
  custom_reads <- isoformCount2Reads(custom,genome,bed,file.path(folder,"custom.gz"),
                                    sep=":",batch_reads=2)
  expect_identical(as.character(ShortRead::sread(custom_reads)),as.character(ShortRead::sread(full)))
  expect_error(reference_seq(genome,"absent",1,2),"outside")
})

test_that("UMI gene errors fail by default and remain visible in explicit partial results", {
  env <- new.env(parent=environment(umi_count))
  env$gene_umi_count <- function(...) stop("deliberate graph failure")
  fun <- umi_count; environment(fun) <- env
  data <- data.frame(gene=rep("g",3),barcode="c",umi="ACGT",isoform="1,10",polyA=1)
  qual <- data.frame(needle=4,count=3)
  strands <- data.frame(gene="g",strand="+")
  expect_error(fun(data,qual,strands),"deliberate graph failure")
  partial <- fun(data,qual,strands,error_policy="continue")
  expect_identical(attr(partial,"umi_qc")$status,"failed")
  expect_equal(attr(partial,"umi_qc")$input_reads,3)
})

